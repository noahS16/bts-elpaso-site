let currentLang = localStorage.getItem('lang') || 'en';

applyTranslations();
setupToggle();

export function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        if (!el.dataset.i18nDefault) {
            el.dataset.i18nDefault = el.textContent;
        }
        el.textContent = currentLang === 'es'
            ? (translations.es[el.dataset.i18n] ?? el.dataset.i18nDefault)
            : el.dataset.i18nDefault;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        if (!el.dataset.i18nDefaultPlaceholder) {
            el.dataset.i18nDefaultPlaceholder = el.placeholder;
        }
        el.placeholder = currentLang === 'es'
            ? (translations.es[el.dataset.i18nPlaceholder] ?? el.dataset.i18nDefaultPlaceholder)
            : el.dataset.i18nDefaultPlaceholder;
    });
}



const onLangChangeCallbacks = [];

export function onLangChange(fn) {
    onLangChangeCallbacks.push(fn);
}

export function toggleLang() {
    currentLang = currentLang === 'en' ? 'es' : 'en';
    localStorage.setItem('lang', currentLang);
    applyTranslations();
    onLangChangeCallbacks.forEach(fn => fn(currentLang));
}


export function getCurrentLang() {
    return currentLang;
}

function updatePill(lang) {
    [
        { optId: 'optEN', pillId: 'langPill' },
        { optId: 'optENMobile', pillId: 'langPillMobile' },
    ].forEach(({ optId, pillId }) => {
        const opt = document.getElementById(optId);
        const pill = document.getElementById(pillId);
        if (!opt || !pill) return;
        pill.style.width = opt.offsetWidth + 'px';
        pill.style.transform = lang === 'en'
            ? 'translateX(0)'
            : `translateX(${opt.offsetWidth}px)`;
    });
}

export function setupToggle() {
    ['langToggle', 'langToggleMobile'].forEach(id => {
        document.getElementById(id)?.addEventListener('click', () => {
            toggleLang();
            const lang = getCurrentLang();
            document.getElementById('optEN')?.classList.toggle('active', lang === 'en');
            document.getElementById('optES')?.classList.toggle('active', lang === 'es');
            document.getElementById('optENMobile')?.classList.toggle('active', lang === 'en');
            document.getElementById('optESMobile')?.classList.toggle('active', lang === 'es');
            updatePill(lang);
        });
    });
    // Sync btn
    const lang = getCurrentLang();
    syncActiveClasses(lang);

    requestAnimationFrame(() => updatePill(getCurrentLang()));
}

function syncActiveClasses(lang) {
    document.getElementById('optEN')?.classList.toggle('active', lang === 'en');
    document.getElementById('optES')?.classList.toggle('active', lang === 'es');
    document.getElementById('optENMobile')?.classList.toggle('active', lang === 'en');
    document.getElementById('optESMobile')?.classList.toggle('active', lang === 'es');
}
